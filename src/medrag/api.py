"""FastAPI service: retrieval + grounded answers + logging + Prometheus metrics.

Endpoints
  GET  /              demo page
  GET  /health        readiness, model version, generator mode
  POST /search        ranked NIH passages
  POST /ask           answer with numbered citations
  POST /feedback      thumbs up/down on a previous answer
  GET  /metrics       Prometheus metrics
  GET  /admin/logs    recent request logs (needs MEDRAG_ADMIN_TOKEN)
"""
from __future__ import annotations

import os
import time
import uuid
from collections import defaultdict, deque
from contextlib import asynccontextmanager
from pathlib import Path

from fastapi import FastAPI, Header, HTTPException, Request
from fastapi.responses import HTMLResponse, Response
from prometheus_client import CONTENT_TYPE_LATEST, Counter, Histogram, generate_latest
from pydantic import BaseModel, Field

from . import __version__
from .config import get_settings
from .generate import Generator, Prompt
from .logsink import RequestLogger
from .retrieval import Bundle
from .text import redact

REQUESTS = Counter("medrag_requests_total", "Requests", ["endpoint", "status"])
LATENCY = Histogram("medrag_request_seconds", "End-to-end latency", ["endpoint"],
                    buckets=(0.01, 0.025, 0.05, 0.1, 0.25, 0.5, 1, 2, 5, 10))
TOP_SCORE = Histogram("medrag_top_score", "Retrieval score of the best hit",
                      buckets=(0.01, 0.02, 0.05, 0.1, 0.5, 1, 2, 5, 10, 20, 40))
LOW_CONF = Counter("medrag_low_confidence_total", "Queries whose best hit is below the reference threshold")
GEN = Counter("medrag_generation_total", "Answers by generation mode", ["mode"])
GEN_ERR = Counter("medrag_generation_errors_total", "LLM failures that fell back to extractive answers")
FEEDBACK = Counter("medrag_feedback_total", "User feedback", ["rating"])

STATE: dict = {}
_RATE: dict[str, deque] = defaultdict(deque)
RATE_LIMIT_PER_MIN = 20


@asynccontextmanager
async def lifespan(app: FastAPI):
    s = get_settings()
    STATE["settings"] = s
    STATE["bundle"] = Bundle.load(s.bundle_dir) if (Path(s.bundle_dir) / "manifest.json").exists() else None
    prompt = Prompt.load(s.prompt_path)
    STATE["prompt"] = prompt
    STATE["generator"] = Generator(prompt, s.llm_api_key, s.llm_base_url, s.llm_model, s.llm_timeout_s,
                                   max_tokens=s.llm_max_tokens, reasoning_effort=s.llm_reasoning_effort or None)
    STATE["logger"] = RequestLogger(s.log_dir, s.log_bucket, s.log_prefix, s.s3_endpoint_url,
                                    s.log_flush_records, s.log_flush_seconds)
    STATE["started"] = time.time()
    if STATE["bundle"] is not None:
        STATE["bundle"].search("warm up the index", 1)  # load lazy models before the first user request
    yield
    STATE["logger"].close()


app = FastAPI(title="MedRAG Ops", version=__version__, lifespan=lifespan)


class Query(BaseModel):
    query: str = Field(..., min_length=3, description="A consumer health question")
    k: int = Field(5, ge=1, le=10)


class Feedback(BaseModel):
    request_id: str
    rating: str = Field(..., pattern="^(up|down)$")
    comment: str | None = Field(None, max_length=500)


def _bundle() -> Bundle:
    b = STATE.get("bundle")
    if b is None:
        raise HTTPException(503, "No model bundle loaded. Run `medrag export` or check MEDRAG_BUNDLE_DIR.")
    return b


def _is_admin(request: Request) -> bool:
    token = STATE["settings"].admin_token
    return bool(token) and request.headers.get("x-admin-token") == token


def _source(request: Request) -> str:
    """Traffic generated by `medrag simulate` (admin token) is labelled so dashboards can separate it."""
    return "simulated" if _is_admin(request) and request.headers.get("x-traffic-source") == "simulated" else "user"


def _check_rate(request: Request) -> None:
    if _is_admin(request):
        return
    ip = (request.headers.get("x-forwarded-for") or (request.client.host if request.client else "?")).split(",")[0]
    q, now = _RATE[ip], time.time()
    while q and now - q[0] > 60:
        q.popleft()
    if len(q) >= RATE_LIMIT_PER_MIN:
        raise HTTPException(429, "Too many requests, please wait a minute.")
    q.append(now)


def _hits_public(hits: list[dict]) -> list[dict]:
    return [{"rank": h["rank"], "score": h["score"], "source": h["source"], "focus": h["focus"],
             "question": h["question"], "url": h["url"], "text": h["body"], "chunk_id": h["chunk_id"]} for h in hits]


def _retrieve(q: Query, endpoint: str):
    s = STATE["settings"]
    if len(q.query) > s.max_query_chars:
        raise HTTPException(422, f"Query longer than {s.max_query_chars} characters.")
    b = _bundle()
    t0 = time.perf_counter()
    hits = b.search(q.query, q.k)
    retrieval_ms = 1000 * (time.perf_counter() - t0)
    top = hits[0]["score"] if hits else 0.0
    TOP_SCORE.observe(top)
    thr = b.manifest.get("monitoring", {}).get("low_confidence_threshold", 0.0)
    low = top < thr
    if low:
        LOW_CONF.inc()
    return b, hits, retrieval_ms, top, low


def _log(endpoint, rid, q, hits, top, low, latency_ms, retrieval_ms, status, extra=None):
    b = STATE.get("bundle")
    STATE["logger"].log({
        "request_id": rid, "endpoint": endpoint, "status": status, "query": redact(q.query)[:1000], "k": q.k,
        "top_score": round(top, 6), "low_confidence": bool(low),
        "top_pairs": [h["pair_id"] for h in hits[:5]], "latency_ms": round(latency_ms, 1),
        "retrieval_ms": round(retrieval_ms, 1), "model_version": b.version if b else None, **(extra or {})})


@app.get("/health")
def health():
    b = STATE.get("bundle")
    g: Generator = STATE["generator"]
    return {"status": "ok" if b else "degraded", "model_version": b.version if b else None,
            "retriever": b.manifest.get("name") if b else None, "chunks": len(b.chunks) if b else 0,
            "generator": g.mode, "llm_model": g.model if g.mode == "llm" else None,
            "prompt_version": STATE["prompt"].version, "app_version": __version__,
            "uptime_s": round(time.time() - STATE["started"], 1)}


@app.post("/search")
def search(q: Query, request: Request):
    _check_rate(request)
    rid, t0 = uuid.uuid4().hex[:12], time.perf_counter()
    with LATENCY.labels("search").time():
        b, hits, rms, top, low = _retrieve(q, "search")
    ms = 1000 * (time.perf_counter() - t0)
    _log("search", rid, q, hits, top, low, ms, rms, 200, {"source": _source(request)})
    REQUESTS.labels("search", "200").inc()
    return {"request_id": rid, "model_version": b.version, "low_confidence": low,
            "latency_ms": round(ms, 1), "hits": _hits_public(hits)}


@app.post("/ask")
def ask(q: Query, request: Request):
    _check_rate(request)
    rid, t0 = uuid.uuid4().hex[:12], time.perf_counter()
    with LATENCY.labels("ask").time():
        b, hits, rms, top, low = _retrieve(q, "ask")
        ans = STATE["generator"].answer(q.query, hits)
    GEN.labels(ans.mode).inc()
    if ans.error:
        GEN_ERR.inc()
    ms = 1000 * (time.perf_counter() - t0)
    _log("ask", rid, q, hits, top, low, ms, rms, 200,
         {"source": _source(request), "gen_mode": ans.mode, "gen_ms": round(ans.latency_ms, 1), "gen_error": ans.error,
          "citations": ans.citations, "answer_chars": len(ans.text), "prompt_version": STATE["prompt"].version})
    REQUESTS.labels("ask", "200").inc()
    return {"request_id": rid, "answer": ans.text, "citations": ans.citations, "mode": ans.mode,
            "low_confidence": low, "disclaimer": STATE["prompt"].disclaimer, "model_version": b.version,
            "latency_ms": round(ms, 1), "sources": _hits_public(hits)}


@app.post("/feedback")
def feedback(f: Feedback):
    FEEDBACK.labels(f.rating).inc()
    STATE["logger"].log({"endpoint": "feedback", "request_id": f.request_id, "rating": f.rating,
                         "comment": redact(f.comment or "")[:500], "status": 200})
    return {"ok": True}


@app.get("/metrics")
def metrics():
    return Response(generate_latest(), media_type=CONTENT_TYPE_LATEST)


@app.get("/admin/logs")
def admin_logs(limit: int = 500, x_admin_token: str | None = Header(None)):
    token = STATE["settings"].admin_token
    if not token or x_admin_token != token:
        raise HTTPException(401, "admin token required")
    return {"rows": STATE["logger"].recent(min(limit, 5000))}


@app.post("/admin/flush")
def admin_flush(x_admin_token: str | None = Header(None)):
    """Push buffered request logs to the bucket now (used by the monitoring workflow)."""
    token = STATE["settings"].admin_token
    if not token or x_admin_token != token:
        raise HTTPException(401, "admin token required")
    lg = STATE["logger"]
    s = STATE["settings"]
    return {"flushed": lg.flush(), "uploaded_batches": lg.uploaded_batches, "upload_errors": lg.upload_errors,
            "last_error": lg.last_error,
            # which settings are present (never their values), to debug a misconfigured host
            "config": {"bucket": s.log_bucket, "endpoint_url": s.s3_endpoint_url,
                       "aws_access_key_id_set": bool(os.environ.get("AWS_ACCESS_KEY_ID")),
                       "aws_secret_access_key_set": bool(os.environ.get("AWS_SECRET_ACCESS_KEY")),
                       "aws_default_region": os.environ.get("AWS_DEFAULT_REGION")}}


@app.exception_handler(HTTPException)
async def _count_errors(request: Request, exc: HTTPException):
    from fastapi.responses import JSONResponse
    REQUESTS.labels(request.url.path.strip("/") or "root", str(exc.status_code)).inc()
    return JSONResponse({"detail": exc.detail}, status_code=exc.status_code)


@app.get("/", response_class=HTMLResponse)
def home():
    return (Path(__file__).parent / "static" / "index.html").read_text()
